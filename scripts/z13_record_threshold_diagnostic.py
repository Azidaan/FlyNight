"""Record threshold-rounding audit without replacing old scientific evidence."""
import json
from datetime import datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def main():
    now = datetime.now().astimezone()
    p = ROOT / 'experiments/project_history.json'
    data = json.loads(p.read_text(encoding='utf-8'))
    parent = next(e for e in data['experiments'] if e['id'] == 'fly_object_readout_z13_v1')
    parent['state'] = 'inconclusive'
    values = {
        'summary': 'Обучение B/C/D завершено; исходный округлённый перебор не выбрал τ. Найдена воспроизводимая ошибка полноты перебора; её влияние на модели проверяется отдельно.',
        'decision': 'Приостановить окончательный отрицательный вердикт до одного повтора предсказаний на прежних 26 train и точного перебора τ. Обучение не повторять, критерии 90% и 50 вмешательств не менять. Dev/MASA и отложенные val не запускать.',
        'cannot_claim': 'Исходные tau=null — подтверждённый результат округлённого перебора, но не доказательство отсутствия любого допустимого τ. На искусственном примере ошибка округления воспроизведена; причиной реального провала она пока не установлена. HOTA и причина недостаточного качества не измерены.',
    }
    for field, value in values.items():
        if parent.get(field) and parent[field] != value:
            parent.setdefault('revisions', []).append({'date': '2026-10-13', 'commit': 'f4c09b0', 'field': field, 'old': parent[field], 'reason': 'Найден синтетически воспроизводимый пропуск допустимого порога из-за округления; влияние на реальные модели неизвестно'})
        parent[field] = value
    parent.pop('done', None)
    if not any(e['id'] == 'z13_threshold_diagnostic_v1' for e in data['experiments']):
        data['experiments'].append({
            'id': 'z13_threshold_diagnostic_v1', 'title': 'З13: один повтор выбора τ без округления и разложение ошибок',
            'area': parent['area'], 'state': 'running', 'started': '2026-10-13',
            'question': 'Пропустил ли округлённый перебор рабочий порог и чем ограничены поправки готовых B/C/D?',
            'hypothesis': 'Округление может объединять разные наборы вмешательств; реальное влияние неизвестно. Отдельно проверяются локализация и ранжирование полезных поправок.',
            'expected': 'Автор разрешил до 10 минут GPU. Только фиксированные модели B/C/D, прежние 26 train без возмущения; сохранить предсказания. Перебрать все точные уникальные уверенности, не разделять равные оценки. Исходные 90%/50 сохраняются. Не переобучать, не использовать dev/val.',
            'acceptance': [
                {'criterion': 'Для B/C/D сохранены предсказания и все точные границы τ; повтор завершён в лимите 10 минут', 'met': None},
                {'criterion': 'Округление изменило допуск хотя бы одной реальной модели: исходный tau=null, точный τ существует при прежних 90%/50', 'met': None},
            ], 'evidence': [{'kind': 'file', 'ref': 'scripts/z13_threshold_diagnostic.py', 'claim': 'Перебор полных границ и ограниченный повтор предсказаний'}],
        })
    p.write_text(json.dumps(data, ensure_ascii=False, indent=1) + '\n', encoding='utf-8')
    plan = ROOT / 'dissertation/ЕДИНЫЙ_ПЛАН.md'
    t = plan.read_text(encoding='utf-8')
    entry = f'''**13.10.2026, {now:%H:%M} MSK** — З13: ошибка округления τ воспроизведена; разрешена одна диагностика готовых моделей

*Поправка собственного вывода.* Фраза «допустимого порога нет» была слишком сильной: подтверждено только, что `scripts/z13_train.py:choose_tau` не выбрал порог среди округлённых до четырёх знаков уверенностей. Синтетический пример: 50 успешных с уверенностью 0,700049 и 7 неуспешных с 0,700011; исходный код возвращает τ=null, точный порог 0,700049 даёт 50/50 успехов. Это ошибка полноты перебора, её участие в реальном отрицательном результате ещё не установлено. Ранее записанный итог сохранён в revisions карточки, состояние временно inconclusive.

*Постановка (`z13_threshold_diagnostic_v1`).* Автор разрешил до 10 минут GPU на один повтор предсказаний готовых B/C/D на прежних 26 train. Обучение, dev/MASA и отложенные val не запускаются. Сохранить все предсказания; сравнить исходный и точный перебор с теми же условиями минимум 50 вмешательств и 90% успехов. Разложить недостаточную точность на отсутствие цели, неточную локализацию и отсутствие улучшения против штатного прогноза; показать число успешных поправок независимо от уверенности. Если точный перебор тоже не даёт τ, округление не объясняет отказ модели по этому правилу. Если даёт, сначала записать исправление измерения, не объявляя прирост HOTA.

'''
    marker = '## Журнал изменений\n\n'
    assert marker in t
    if entry.splitlines()[0] not in t:
        plan.write_text(t.replace(marker, marker + entry, 1), encoding='utf-8')


if __name__ == '__main__':
    main()
