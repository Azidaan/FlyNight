"""Локальные ветви способов проверки: без структурных связей с другими графами."""
from scripts.obsidian_b123_literature import SOURCES, RELATIONS, path as paper_path

START='<!-- hypothesis-tree-children:start -->'
END='<!-- hypothesis-tree-children:end -->'
FOLDER='Гипотезы — подходы'
TITLES={
    'HY26-1':{
        'busca':'Б1.1 — Проверять продолжение объекта по истории внешнего вида — BUSCA',
        'ltr':'Б1.2 — Отделять объект от соседа с помощью маски — LTR',
        'masa':'Б1.3 — Сшивать обрывки по внешнему виду — признаки MASA'},
    'HY26-2':{
        'busca':'Б2.1 — Сравнить исправление до и после обнаружения — BUSCA',
        'ltr':'Б2.2 — Сравнить временные признаки с переносом маски — LTR'},
    'HY26-3':{
        'busca':'Б3.1 — Хранить историю внешнего вида в памяти объекта — BUSCA',
        'ltr':'Б3.2 — Хранить маску и её состояние в памяти объекта — LTR'}}

ROLES={
    ('HY26-1','busca'):'Кандидат для развития сопоставления и проверки продолжения объекта. Опубликованная BUSCA не является нашей временной поправкой FlyVis.',
    ('HY26-1','ltr'):'Возможный способ подготовить более чистое представление объекта. Нынешняя Б1 маски не использует; такая замена ещё не проверена.',
    ('HY26-2','busca'):'Альтернатива по месту вмешательства: Б2 работает до обнаружения, BUSCA — после сопоставления. Это связь для сравнения подходов, а не реализация Б2.',
    ('HY26-2','ltr'):'Альтернатива восстановлению пропуска через признаки детектора. LTR продолжает маску после потери назначения; эти механизмы нельзя считать одинаковыми.',
    ('HY26-3','busca'):'Пример того, какую наблюдаемую историю может использовать память объекта. Структура связей FlyVis в этой работе не проверяется.',
    ('HY26-3','ltr'):'Возможное содержание состояния памяти: маска конкретного объекта и история её переноса. Польза коннектома из этого не следует.'}


def child_paths():
    return {f'{FOLDER}/{title}' for branches in TITLES.values() for title in branches.values()}


def branch_key(card):
    return next((tag for tag in card.get('tags',[]) if tag in TITLES),None)


def section(card):
    key=branch_key(card)
    if key is None:return ''
    text=START+'\n## Подходы и способы проверки\n\n'
    text+='Дочерние узлы принадлежат только этому дереву. Переходы из них к статьям, карточкам и результатам — стелс-связи. Наличие ветви не означает, что её эффективность проверена.\n\n'
    for title in TITLES[key].values():text+=f'[[{FOLDER}/{title}|{title}]]\n\n'
    return text+END+'\n'


def build(vault,history,card_paths,ref,fm):
    for card in history['experiments']:
        key=branch_key(card)
        if key is None:continue
        parent=card_paths[card['id']]
        for method,title in TITLES[key].items():
            if method=='masa':
                from scripts.obsidian_masa_hypothesis import build as build_masa
                build_masa(vault,parent,ref,fm)
                continue
            body=f'# {title}\n\n↑ [[{parent}|{card["title"]}]]\n\n'
            body+='**Статус:** способ проверки или развития; научная эффективность в нашем проекте пока не подтверждена. Это не отдельный завершённый эксперимент.\n\n'
            body+='## Зачем эта ветвь\n\n'+ROLES[key,method]+'\n\n'+RELATIONS[key][method]+'\n\n'
            body+='## Что должно проверить применение\n\n'
            if key=='HY26-2':
                body+='Раздельно измерить исправление признаков до обнаружения и восстановление траекторий после сопоставления. Сохранить одинаковые исходные данные и показать влияние на пропуски, ложные рамки и HOTA. Сравнение ещё не проведено.\n\n'
            elif key=='HY26-3':
                body+='Сравнить одинаковое содержание памяти при структуре связей FlyVis, перестроенных связях и обычной временной сети. Прибавка от истории или маски сама по себе не доказывает пользу анатомии.\n\n'
            else:
                body+='Сравнить исходный трекер, простое продолжение потерянного объекта и проверку продолжения по наблюдаемой истории. Отдельно учитывать полезные восстановления и ложные продолжения.\n\n'
            body+='## Источник и результаты — стелс-связи\n\n'
            body+=ref('',paper_path(method),SOURCES[method]['title'])+'\n\n'
            body+=f'[Первичная публикация]({SOURCES[method]["url"]})\n\n'
            if method=='busca':
                body+='Авторские исходники и веса готовятся к переносу. Точные условия и текущие файлы: `runs/b123_20261027/`. Это ещё не измеренная польза BUSCA на нашем стенде.\n\n'
            else:
                body+='Точная реализация LTR и её веса ещё проверяются. SGAR-MOT — отдельная работа; её нельзя подменять этим названием.\n\n'
            body+='## Связанные проверки проекта\n\n'
            for ident in ('recovery_motion_output_control_v1','b1_temporal_residual_training_v1'):
                if ident in card_paths:
                    entry=next(c for c in history['experiments'] if c['id']==ident)
                    body+=ref('',card_paths[ident],entry['title'])+'\n\n'
            vault.write(f'{FOLDER}/{title}.md',fm({'tags':['гипотезы-подход','проверка-гипотезы/не-завершена'],
                'родитель':card['id'],'роль':'подход к проверке; не доказательство','источник':method.upper()})+body)
