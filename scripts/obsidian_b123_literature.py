def path(key):return GROUP+'/'+SOURCES[key]['title']


def branch_tag(card):
    tags=[t for t in card.get('tags',[]) if t in RELATIONS]
    return tags[0] if len(tags)==1 else None


def branch_section(card,ref):
    tag=branch_tag(card)
    if tag is None:return ''
    text=START+'\n## Связанные исследования — стелс-связи\n\n'
    text+='Кликабельные переходы без видимых рёбер графа. Связь с публикацией не означает подтверждение нашей гипотезы.\n\n'
    for key,source in SOURCES.items():
        text+=ref('',path(key),source['title'])+'\n\n'+RELATIONS[tag][key]+'\n\n'
    return text+END+'\n'


def with_section(original,section):
    body=re.sub(re.escape(START)+r'.*?'+re.escape(END)+r'\s*','',original,flags=re.S)
    return body.rstrip()+'\n\n'+section


